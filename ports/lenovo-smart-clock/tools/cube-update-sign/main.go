// cube-update-sign makes an experimental signed manifest for private images.
// It never copies, uploads or publishes images or signing keys.
package main

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"crypto/x509"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

var faultMarker = []byte("CUBE-OTA-FAULT-TEST-DO-NOT-RELEASE")

func hasFaultMarker(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	buf := make([]byte, 1024*1024)
	tail := make([]byte, 0, len(faultMarker)-1)
	for {
		n, readErr := f.Read(buf)
		chunk := append(tail, buf[:n]...)
		if bytes.Contains(chunk, faultMarker) {
			return true, nil
		}
		keep := len(faultMarker) - 1
		if len(chunk) < keep {
			keep = len(chunk)
		}
		tail = append(tail[:0], chunk[len(chunk)-keep:]...)
		if readErr == io.EOF {
			return false, nil
		}
		if readErr != nil {
			return false, readErr
		}
	}
}

type manifest struct {
	Format       int    `json:"format"`
	Board        string `json:"board"`
	Version      string `json:"version"`
	Sequence     uint64 `json:"sequence"`
	Slot         string `json:"slot"`
	SystemSize   int64  `json:"system_size"`
	SystemSHA256 string `json:"system_sha256"`
	BootSize     int64  `json:"boot_size"`
	BootSHA256   string `json:"boot_sha256"`
}

var versionPattern = regexp.MustCompile(`^[0-9A-Za-z][0-9A-Za-z._+-]{0,63}$`)

// No key is generated by this command; the caller manages the private key and
// pins the corresponding public key separately. Refuse keys under any Git
// worktree even if ignored, so a later add cannot publish them by accident.
func readKey(path string) (ed25519.PrivateKey, error) {
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil {
		return nil, err
	}
	resolved, err = filepath.Abs(resolved)
	if err != nil {
		return nil, err
	}
	for dir := filepath.Dir(resolved); ; dir = filepath.Dir(dir) {
		if _, err := os.Lstat(filepath.Join(dir, ".git")); err == nil {
			return nil, errors.New("private key must be outside every Git worktree")
		} else if !os.IsNotExist(err) {
			return nil, errors.New("could not check private key location")
		}
		if filepath.Dir(dir) == dir {
			break
		}
	}
	if _, err := exec.LookPath("git"); err != nil {
		return nil, errors.New("git is required to check the key location")
	}
	cmd := exec.Command("git", "-C", filepath.Dir(resolved), "rev-parse", "--absolute-git-dir")
	if err := cmd.Run(); err == nil {
		return nil, errors.New("private key must be outside every Git worktree")
	} else if e, ok := err.(*exec.ExitError); !ok || e.ExitCode() != 128 {
		return nil, errors.New("could not check private key location")
	}
	info, err := os.Stat(resolved)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > 4096 {
		return nil, errors.New("invalid private key file")
	}
	if runtime.GOOS != "windows" && info.Mode().Perm()&0077 != 0 {
		return nil, errors.New("private key file must not be accessible to others")
	}
	data, err := os.ReadFile(resolved)
	if err != nil {
		return nil, err
	}
	block, rest := pem.Decode(data)
	if block == nil || block.Type != "PRIVATE KEY" || len(strings.TrimSpace(string(rest))) != 0 {
		return nil, errors.New("expected one PKCS#8 private key")
	}
	k, err := x509.ParsePKCS8PrivateKey(block.Bytes)
	if err != nil {
		return nil, err
	}
	key, ok := k.(ed25519.PrivateKey)
	if !ok {
		return nil, errors.New("private key is not Ed25519")
	}
	return key, nil
}

func hashFile(path string) (int64, string, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, "", err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return 0, "", err
	}
	if !info.Mode().IsRegular() || info.Size() <= 0 {
		return 0, "", errors.New("image is not a regular file")
	}
	h := sha256.New()
	n, err := io.Copy(h, f)
	if err != nil || n != info.Size() {
		return 0, "", errors.New("image read was incomplete")
	}
	return n, hex.EncodeToString(h.Sum(nil)), nil
}

func checkImages(system, boot, slot string) error {
	s, err := os.Open(system)
	if err != nil {
		return err
	}
	defer s.Close()
	var magic [2]byte
	if _, err := s.ReadAt(magic[:], 1080); err != nil || magic != [2]byte{0x53, 0xef} {
		return errors.New("system image is not ext4")
	}
	b, err := os.Open(boot)
	if err != nil {
		return err
	}
	defer b.Close()
	info, err := b.Stat()
	if err != nil {
		return err
	}
	header := make([]byte, 1632)
	if _, err := b.ReadAt(header, 0); err != nil {
		return errors.New("boot header truncated")
	}
	if string(header[:8]) != "ANDROID!" {
		return errors.New("invalid boot magic")
	}
	ks, rs, ss := binary.LittleEndian.Uint32(header[8:]), binary.LittleEndian.Uint32(header[16:]), binary.LittleEndian.Uint32(header[24:])
	page, version := binary.LittleEndian.Uint32(header[36:]), binary.LittleEndian.Uint32(header[40:])
	if version != 0 || page < 1632 || page > 65536 || page&(page-1) != 0 || ks == 0 || rs == 0 {
		return errors.New("unsupported boot header")
	}
	align := func(n uint32) int64 { return (int64(n) + int64(page) - 1) / int64(page) * int64(page) }
	if int64(page)+align(ks)+align(rs)+int64(ss) > info.Size() {
		return errors.New("boot components exceed image")
	}
	for _, v := range header[608:] {
		if v != 0 {
			return errors.New("extended command line unsupported")
		}
	}
	cmd := header[64:576]
	if i := strings.IndexByte(string(cmd), 0); i >= 0 {
		for _, v := range cmd[i:] {
			if v != 0 {
				return errors.New("invalid command line padding")
			}
		}
		cmd = cmd[:i]
	}
	root, keep := 0, false
	for _, v := range cmd {
		if v < 32 || v > 126 {
			return errors.New("invalid command line")
		}
	}
	for _, word := range strings.Fields(string(cmd)) {
		if strings.HasPrefix(word, "techo5.cube.root=") {
			root++
			if word != "techo5.cube.root=system_"+slot {
				return errors.New("boot image targets the wrong slot")
			}
		}
		if word == "keep_initramfs" {
			keep = true
		}
	}
	if root != 1 || !keep {
		return errors.New("missing boot arguments")
	}
	return nil
}

func main() {
	keyPath := flag.String("key", "", "external PKCS#8 Ed25519 private key")
	system := flag.String("system", "", "private ext4 system image")
	boot := flag.String("boot", "", "slot-specific private Android boot image")
	slot := flag.String("slot", "", "target slot a or b")
	version := flag.String("version", "", "release version")
	sequence := flag.Uint64("sequence", 0, "monotonic signed release sequence")
	out := flag.String("out", "", "new private directory for manifest and signature")
	allowFault := flag.Bool("allow-fault-test", false, "allow an intentionally failing private test image; never use for a release")
	flag.Parse()
	if err := run(*keyPath, *system, *boot, *slot, *version, *sequence, *out, *allowFault); err != nil {
		fmt.Fprintln(os.Stderr, "signing stopped:", err)
		os.Exit(1)
	}
	fmt.Println("Created a signed private manifest; no image or key was copied or published.")
}

func run(keyPath, system, boot, slot, version string, sequence uint64, out string, allowFault bool) error {
	if keyPath == "" || system == "" || boot == "" || out == "" || (slot != "a" && slot != "b") || !versionPattern.MatchString(version) || sequence == 0 {
		return errors.New("all arguments are required and must be valid")
	}
	key, err := readKey(keyPath)
	if err != nil {
		return err
	}
	if err := checkImages(system, boot, slot); err != nil {
		return err
	}
	fault, err := hasFaultMarker(system)
	if err != nil {
		return err
	}
	if fault && !allowFault {
		return errors.New("fault-injection image requires --allow-fault-test and must never be released")
	}
	if allowFault && !fault {
		return errors.New("fault-test override requires a marked fault-injection image")
	}
	ss, sh, err := hashFile(system)
	if err != nil {
		return err
	}
	bs, bh, err := hashFile(boot)
	if err != nil {
		return err
	}
	if ss > 1024*1024*1024 || bs > 64*1024*1024 {
		return errors.New("image is too large")
	}
	payload, err := json.Marshal(manifest{1, "cube", version, sequence, slot, ss, sh, bs, bh})
	if err != nil {
		return err
	}
	sig := ed25519.Sign(key, payload)
	if err := os.Mkdir(out, 0700); err != nil {
		return err
	}
	for _, v := range []struct {
		name string
		data []byte
	}{{"manifest.json", payload}, {"manifest.sig", sig}} {
		f, err := os.OpenFile(filepath.Join(out, v.name), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if err != nil {
			return err
		}
		if _, err := f.Write(v.data); err != nil {
			f.Close()
			return err
		}
		if err := f.Sync(); err != nil {
			f.Close()
			return err
		}
		if err := f.Close(); err != nil {
			return err
		}
	}
	return nil
}
